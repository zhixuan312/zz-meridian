/**
 * Build cli/payload/: the template snapshot the package carries.
 *
 *   node cli/scripts/build-payload.ts            the committed tree at HEAD (what a release ships)
 *   node cli/scripts/build-payload.ts --worktree the working tree's tracked files, for trying a change before committing
 *
 * From git, never from a walk of the folder: a build output, a local .env or a stray file cannot reach the package.
 * The package's own source, the CI workflows and agent settings stay out.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { shippedPath } from '../src/files.ts';

const ROOT = path.resolve(import.meta.dirname, '../..');
const OUT = path.join(ROOT, 'cli/payload');
const worktree = process.argv.includes('--worktree');

/** Never shipped: the package itself, CI, agent settings, Meridian's own demo deployment, and anything that could hold a secret. */
// Meridian's tests are its own proof and stay out: a project is proven by its gates and by its own tests. Only
// `tests/setup.ts`, which every project's test run loads, and `tests/examples/`, the team's starting examples, ship. Every
// other path under tests/ stays out, helpers included. The fixtures under scripts/fixtures/ serve those tests alone and
// import the template's own team-owned starters.
// Three more groups no route reads. Meridian's own documentation: `docs/`, `decisions/` and `CONTRIBUTING.md`, the
// contributor guide for the repository itself (the CHANGELOG ships whole). The Atlas, Meridian's documentation site:
// `app/system/` and the modules in `src/system/` only it imports. The previews the Atlas renders: every card's
// `preview.tsx` (the card's README ships). `src/system/fixtures/` and `sample-cells.tsx`/`specimen.tsx` stay: the pages read them.
export const PAYLOAD_EXCLUDE = /^(cli\/|docs\/|decisions\/|CONTRIBUTING\.md$|app\/system\/|src\/system\/(?:content\.ts|hero\.tsx|markdown\.tsx|page-stage\.tsx|atlas-shell\.tsx|card-stage\.tsx|preview-loaders\.ts|preview-loading\.tsx|strata\.tsx|token-view\.tsx|tokens-data\.ts|registry\.ts)$|src\/components\/.*\/preview\.tsx$|\.github\/|\.claude\/|\.agents\/|\.mma\/|out\/|node_modules\/|scripts\/fixtures\/|tests\/(?!setup\.ts$|examples\/)|scripts\/perf-history\.json$|\.nvmrc$|.*\.tsbuildinfo$|(Dockerfile|captain-definition|\.dockerignore)$)|(?:^|\/)\.env(?!\.example$)[^/]*(?:\/|$)/;

if (import.meta.main) {
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });

  // HEAD: the committed bytes, extracted by git archive whatever the working tree holds now.
  const STAGE = path.join(ROOT, 'cli/.payload-stage');
  fs.rmSync(STAGE, { recursive: true, force: true });
  fs.mkdirSync(STAGE, { recursive: true });
  let from = ROOT;
  let files: string[];
  if (worktree) {
    // The tracked files and the new, untracked source files: a change under review has both, and a release built from
    // HEAD has every file committed before its tarball is made.
    const tracked = execFileSync('git', ['ls-files', '-z'], { cwd: ROOT }).toString('utf8').split('\0').filter(Boolean);
    const fresh = execFileSync('git', ['ls-files', '--others', '--exclude-standard', '-z'], { cwd: ROOT }).toString('utf8').split('\0').filter(Boolean);
    files = [...new Set([...tracked, ...fresh])];
  } else {
    const tar = path.join(STAGE, 'head.tar');
    fs.writeFileSync(tar, execFileSync('git', ['archive', '--format=tar', 'HEAD'], { cwd: ROOT, maxBuffer: 256 * 1024 * 1024 }));
    fs.mkdirSync(path.join(STAGE, 'tree'));
    execFileSync('tar', ['-xf', tar, '-C', path.join(STAGE, 'tree')]);
    from = path.join(STAGE, 'tree');
    files = execFileSync('git', ['ls-tree', '-r', '-z', '--name-only', 'HEAD'], { cwd: ROOT }).toString('utf8').split('\0').filter(Boolean);
  }

  let n = 0;
  for (const f of files.filter((x) => !PAYLOAD_EXCLUDE.test(x))) {
    const src = path.join(from, f);
    const st = fs.lstatSync(src, { throwIfNoEntry: false });
    // A deleted file still in the index, a symbolic link or anything but a plain file is not shipped.
    if (!st?.isFile()) continue;
    const dst = path.join(OUT, shippedPath(f));
    fs.mkdirSync(path.dirname(dst), { recursive: true });
    fs.copyFileSync(src, dst);
    n++;
  }
  // Generate the CLI companion from the payload's source before removing the archived HEAD tree.
  for (const name of ['update-session', 'jsonc']) {
    fs.writeFileSync(
      path.join(ROOT, `cli/src/${name}.ts`),
      `// Generated by cli/scripts/build-payload.ts from scripts/lib/${name}.ts; do not edit.\n`
        + fs.readFileSync(path.join(from, `scripts/lib/${name}.ts`), 'utf8'),
    );
  }
  fs.rmSync(STAGE, { recursive: true, force: true });
  console.log(`payload: ${n} files from ${worktree ? 'the working tree' : 'HEAD'}`);
}
